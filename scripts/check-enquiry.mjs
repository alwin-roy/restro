import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const cache=new Map();
function load(file) {
  const filename=path.resolve(file);
  if(cache.has(filename)) return cache.get(filename).exports;
  const compiled={exports:{}};cache.set(filename,compiled);
  const requireTs=(specifier)=>load(path.resolve('src',specifier.slice(2))+'.ts');
  const code=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
  new Function('require','exports','module',code)(requireTs,compiled.exports,compiled);
  return compiled.exports;
}
const {validateEnquiry:validate,firstInvalidEnquiryField}=load('src/lib/validations/enquiry.ts');
const {enquirySubjects}=load('src/data/enquirySubjects.ts');
const {restaurantContact}=load('src/data/restaurantContact.ts');
const {contactPhoneHref,contactEmailHref,contactSocialHref}=load('src/lib/contact.ts');
const good={name:'Rahul Kumar',email:'customer@example.com',phone:'',subject:'general',message:'Could you share more information about the menu?'};
assert.ok(validate(good).details);
for(const name of ['', '  ', 'Rahul123','John@','12345','A','A'.repeat(101)]) assert.ok(validate({...good,name}).errors.name,name);
for(const name of ['Anjali','Élodie Durand','अंजली शर्मा','李 明','Jose\u0301 Silva']) assert.ok(validate({...good,name}).details,name);
const normalized=validate({...good,name:'  Rahul   Kumar  ',email:'  customer@example.com  '});
assert.equal(normalized.details.name,'Rahul Kumar');assert.equal(normalized.details.email,'customer@example.com');
for(const email of ['', 'customer@gmail','customer@','@gmail.com','a@@gmail.com','a..b@gmail.com','a@-gmail.com','a@gmail..com','a b@gmail.com']) assert.ok(validate({...good,email}).errors.email,email);
assert.ok(validate({...good,email:'customer+enquiry@example.com'}).details);
for(const phone of ['123456789','12345678901','98765abcde','98765 3210','+919876543210','987654321!','          ']) assert.ok(validate({...good,phone}).errors.phone,phone);
const withPhone=validate({...good,phone:'9876543210'});
assert.equal(withPhone.details.phone,'+919876543210');
assert.equal(validate(withPhone.values).details.phone,'+919876543210');
assert.equal(enquirySubjects.length,6);
enquirySubjects.forEach(({value})=>assert.ok(validate({...good,subject:value}).details));
for(const subject of ['', 'unknown','General Enquiry','__proto__']) assert.ok(validate({...good,subject}).errors.subject,subject);
for(const message of ['', ' '.repeat(20),'Too short','x'.repeat(2001)]) assert.ok(validate({...good,message}).errors.message);
assert.ok(validate({...good,message:'x'.repeat(10)}).details);
assert.ok(validate({...good,message:'x'.repeat(2000)}).details);
assert.equal(validate({...good,message:'Hello!\nA menu question, for 2 guests.'}).details.message,'Hello!\nA menu question, for 2 guests.');
const plain='<script>alert("plain text")</script>';
assert.equal(validate({...good,message:plain}).details.message,plain);
assert.equal(firstInvalidEnquiryField({message:'Required',email:'Required'}),'email');
assert.equal(firstInvalidEnquiryField(validate({name:'',email:'',phone:'',subject:'',message:''}).errors),'name');
assert.equal(contactPhoneHref(''),null);
assert.equal(contactEmailHref(''),null);
assert.equal(contactPhoneHref('+91 (98765) 43210'),'tel:+919876543210');
for(const phone of ['12345','tel:+919876543210','javascript:alert(1)']) assert.equal(contactPhoneHref(phone),null);
assert.equal(contactEmailHref('customer@example.com'),'mailto:customer@example.com');
