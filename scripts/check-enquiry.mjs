assert.ok(contactEmailHref('user?subject=test@example.com').includes('%3F'));
for(const platform of ['instagram','facebook','youtube','x']) assert.equal(contactSocialHref(platform,''),null);
assert.equal(contactSocialHref('instagram','https://www.instagram.com/restro'),'https://www.instagram.com/restro');
